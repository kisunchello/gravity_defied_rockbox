#define TWO_PI_F16  (2 * PiF16)   /* 411774 */

int MathF16::multiplyF16(int a, int b)
{
    return (int)((int64_t)a * (int64_t)b >> 16);
}

int MathF16::divideF16(int a, int b)
{
    return (int)(((int64_t)a << 32) / (int64_t)b >> 16);
}

int MathF16::sinF16(int angle)
{
    /* reduce to [0, 2pi) */
    angle %= TWO_PI_F16;
    if (angle < 0)
        angle += TWO_PI_F16;

    int64_t num = (int64_t)angle * 256;
    int idx  = (int)(num / TWO_PI_F16);          /* 0..255 */
    int frac = (int)(num % TWO_PI_F16);
    int a = SIN_TAB[idx & 255];
    int b = SIN_TAB[(idx + 1) & 255];
    return a + (int)((int64_t)(b - a) * frac / TWO_PI_F16);
}

int MathF16::cosF16(int angle)
{
    return sinF16(PiHalfF16 - angle);
}

/* atan of an F16 ratio, result in F16 radians, range (-pi/2, pi/2).
 * Uses atan(x) ~= x/(1 + 0.28*x^2) for |x|<=1 with range reduction. */
int MathF16::atanF16(int z)
{
    int neg = z < 0;
    if (neg) z = -z;

    int res;
    if (z > 65536) {
        /* atan(z) = pi/2 - atan(1/z) */
        int inv = divideF16(65536, z);
        int d = 65536 + multiplyF16(18350, multiplyF16(inv, inv));
        res = PiHalfF16 - divideF16(inv, d);
    } else {
        int d = 65536 + multiplyF16(18350, multiplyF16(z, z));
        res = divideF16(z, d);
    }
    return neg ? -res : res;
}

int MathF16::atan2F16(int dx, int dy)
{
    if ((dy < 0 ? -dy : dy) < 3) {
        return (dx > 0 ? 1 : -1) * PiHalfF16;
    } else {
        int atanVal = atanF16(divideF16(dx, dy));
        if (dx > 0) {
            return dy > 0 ? atanVal : PiF16 + atanVal;
        } else {
            return dy > 0 ? atanVal : atanVal - PiF16;
        }
    }
}
